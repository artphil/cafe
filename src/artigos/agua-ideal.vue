  <h2>Que água usar em casa</h2>
  <ul>
    <li><strong>Água filtrada:</strong> para a maioria das casas, é o melhor começo. Um filtro com carvão ativado tira
      o cloro e já melhora bastante o gosto, sem precisar de mais nada. Se o cheiro da água da torneira já incomoda,
      comece por aqui.</li>
    <li><strong>Água mineral engarrafada:</strong> serve bem, e a escolha pode ser feita pelo rótulo. Procure uma com
      resíduo de evaporação (o total de minerais) entre uns 50 e 150 mg/L e pH perto do neutro. Evite as muito
      mineralizadas.</li>
    <li><strong>Água destilada ou de osmose reversa:</strong> não é boa ideia pura. Sem minerais, o café sai plano e
      pouco extraído.</li>
    <li><strong>Água com gás ou "alcalina" de marca:</strong> evite, o resultado é imprevisível.</li>
  </ul>
  <p>
    Se a sua água da torneira é muito dura, o sinal costuma ser a crosta branca na chaleira. Nesse caso, um filtro
    ajuda, ou vale misturar com uma água mineral mais leve.
  </p>

  <h2>Cuidados com a água na hora de fazer</h2>
  <ul>
    <li><strong>Use água fresca:</strong> evite ferver de novo a água que ficou muito tempo na chaleira.</li>
    <li><strong>Atenção à temperatura:</strong> ferva e espere uns 30 segundos a 1 minuto, para ficar entre 90 e 96 °C
      (veja o ajuste em cada método, como o <a href="./v60.html">V60</a>).</li>
    <li><strong>Mantenha o equipamento limpo:</strong> o calcário acumulado muda o sabor e estraga chaleiras e
      máquinas.</li>
  </ul>

  <h2>Um teste simples</h2>
  <p>
    Prepare o mesmo café, com o mesmo método e a mesma receita, usando duas águas diferentes (por exemplo, a filtrada
    da torneira e uma mineral de rótulo leve). Prove uma depois da outra. A diferença costuma aparecer no aroma e na
    sensação de corpo, e é a melhor forma de saber qual água funciona na sua casa. Para o resto, a
    <a href="./moagem-por-metodo.html">moagem</a> e o <a href="./armazenamento-do-cafe.html">armazenamento</a> do
    café também pesam bastante.
  </p>

  <h2>Erros comuns</h2>
  <ul>
    <li>Usar água da torneira sem filtro, com cloro.</li>
    <li>Usar água destilada achando que "mais pura" é melhor.</li>
    <li>Escolher uma água só pela marca, sem olhar o rótulo.</li>
    <li>Ignorar o calcário na chaleira e na moka.</li>
    <li>Mudar a água e a moagem ao mesmo tempo, sem saber o que causou a diferença.</li>
  </ul>

