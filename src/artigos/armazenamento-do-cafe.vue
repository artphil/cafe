  <h2>Grão inteiro ou moído?</h2>
  <p>
    Sempre que der, compre <strong>grão inteiro</strong> e moa só na hora de preparar. Depois de moído, o café tem
    muito mais superfície exposta ao ar, e os aromas escapam em questão de minutos. O grão inteiro guarda melhor e
    rende uma xícara bem mais viva. Se você não tem moedor, compre o moído em quantidades pequenas e na moagem certa
