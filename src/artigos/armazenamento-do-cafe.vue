    perde qualidade com o tempo, e algumas escolhas simples em casa ajudam o café a manter o sabor por muito mais
    tempo.
  </p>

  <h2>Os quatro inimigos do café</h2>
  <ul>
    <li><strong>Oxigênio:</strong> é um dos que mais aceleram o envelhecimento. Quanto mais ar em contato com o café,
      mais rápido os aromas se perdem e os óleos ficam rançosos.</li>
    <li><strong>Luz:</strong> principalmente a do sol, que acelera a degradação do café. Por isso embalagens claras e
      potes transparentes expostos à luz não são uma boa ideia.</li>
    <li><strong>Calor:</strong> perto do fogão, do forno ou de uma janela ensolarada, o café envelhece mais depressa.
    </li>
    <li><strong>Umidade:</strong> o café absorve água e cheiros do ambiente, o que apaga o sabor e pode até
      estragá-lo.</li>
  </ul>

  <h2>Grão inteiro ou moído?</h2>
  <p>
    Sempre que der, compre <strong>grão inteiro</strong> e moa só na hora de preparar. Depois de moído, o café tem
    muito mais superfície exposta ao ar, e os aromas escapam bem mais depressa. O grão inteiro guarda melhor e rende
    uma xícara mais viva. Se você não tem moedor, compre o moído em quantidades pequenas e na moagem certa
    para o seu método (veja a <a href="./moagem-por-metodo.html">moagem ideal para cada método</a>).
  </p>

  <h2>Onde e como guardar</h2>
  <ul>
    <li><strong>Pote hermético e opaco:</strong> de metal, cerâmica ou vidro escuro, com tampa que vede bem. Nem todo
      pote de cerâmica veda: se a tampa for solta, o ar entra. Se o pote for transparente, deixe dentro do
      armário.</li>
    <li><strong>A embalagem original pode servir:</strong> muitas têm uma válvula que deixa o gás sair sem deixar o ar
      entrar. Depois de aberta, prefira passar o café para um pote; se a embalagem tiver fecho zip, aperte para
      tirar o ar antes de fechar.</li>
    <li><strong>Local fresco, seco e escuro:</strong> um armário longe do fogão e da luz do sol é o ideal.</li>
    <li><strong>Pote só para o café:</strong> evite guardar junto de temperos e outros alimentos de cheiro forte.</li>
  </ul>

  <h2>E a geladeira e o freezer?</h2>
  <p>
    Para o café de todo dia, a <strong>geladeira não é boa ideia</strong>: ela é úmida, cheia de cheiros, e cada vez
    que você abre um pote gelado a umidade do ar condensa no café. O <strong>freezer</strong> pode funcionar para
    guardar uma reserva por mais tempo, mas não é unanimidade entre baristas. Se for usar, vede muito bem e divida em
    porções pequenas, para tirar só o que vai usar. Deixe a porção chegar à temperatura ambiente antes de abrir e não
    volte a congelar o que descongelou.
  </p>

  <h2>Quanto comprar e quanto tempo dura</h2>
  <p>
    Guardado do jeito certo, o café costuma manter o melhor sabor por cerca de
    <strong>2 a 4 semanas depois da torra</strong>. Nos primeiros dias ele ainda libera muito gás, e depois a
    qualidade cai aos poucos. Isso varia com o café e a torra, mas serve como referência. Por isso:
  </p>
  <ul>
    <li>Olhe a <strong>data de torra</strong> no pacote (veja mais sobre isso em
      <a href="./torras.html">torras do café</a>).</li>
    <li>Compre a quantidade que você consegue tomar em 1 a 2 semanas, ou em no máximo 4.</li>
    <li>Prefira comprar pouco e com mais frequência a estocar um pacote grande.</li>
  </ul>

  <h2>Como saber que o café passou do ponto</h2>
  <ul>
    <li><strong>Aroma fraco ou sem graça</strong> ao abrir o pote.</li>
    <li><strong>Cheiro de ranço, papelão ou mofo.</strong></li>
    <li><strong>Pouca espuma no bloom:</strong> café fresco incha e solta gás quando recebe a água (veja o bloom no
      <a href="./v60.html">V60</a>). Café velho quase não reage (em café muito
      recém-torrado, o bloom costuma ser bem intenso, e isso é normal).</li>
    <li><strong>Sabor plano, amadeirado ou amargo</strong>, mesmo com o preparo certo.</li>
  </ul>

  <h2>Erros comuns</h2>
  <ul>
    <li>Guardar o café perto do fogão ou numa bancada ao sol.</li>
    <li>Deixar o pacote aberto, só dobrado.</li>
    <li>Colocar o café na geladeira e tirar e pôr toda hora.</li>
    <li>Comprar café moído em grande quantidade.</li>
    <li>Misturar café novo com o velho no mesmo pote.</li>
  </ul>

  <h2>Resumindo</h2>
  <ul>
    <li>Proteja o café de ar, luz, calor e umidade.</li>
    <li>Prefira grão inteiro e moa na hora.</li>
    <li>Use um pote hermético e opaco, num armário fresco e seco.</li>
    <li>Compre pouco e com frequência, olhando a data de torra.</li>
  </ul>
